// Bundle public/ into a JS module served by the Worker itself.
// (We embed instead of using Workers Static Assets so a deploy needs only one API call
// authenticated with the account API token.)
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { ROOT } from './lib/seed.mjs';

const TYPES = { '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.json': 'application/json; charset=utf-8', '.svg': 'image/svg+xml', '.txt': 'text/plain; charset=utf-8' };
const files = {};
for (const f of fs.readdirSync(path.join(ROOT, 'public'))) {
  const ext = path.extname(f);
  if (!TYPES[ext]) continue;
  const body = fs.readFileSync(path.join(ROOT, 'public', f), 'utf8');
  files['/' + f] = { type: TYPES[ext], etag: '"' + crypto.createHash('sha1').update(body).digest('hex').slice(0, 16) + '"', body };
}
fs.mkdirSync(path.join(ROOT, 'src/generated'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'src/generated/static.js'), `// generated by scripts/build-static.mjs\nexport default ${JSON.stringify(files)};\n`);
console.log('embedded', Object.keys(files).join(', '));
